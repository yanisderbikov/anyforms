-- Лог производства позиции: короткие текстовые записи «что сделали», каждая со своим временем.
CREATE TABLE custom_product_logs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id    BIGINT    NOT NULL REFERENCES custom_product_items (id) ON DELETE CASCADE,
    text       TEXT      NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_custom_product_logs_item_id ON custom_product_logs (item_id);
